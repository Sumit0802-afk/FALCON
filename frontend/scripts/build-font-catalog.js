/**
 * Rebuilds src/data/googleFonts.ts from the public font directories:
 *
 *   Google Fonts   https://fonts.google.com/metadata/fonts
 *   Fontshare      https://api.fontshare.com/v2/fonts?limit=200
 *
 * Only real families with their real weights are listed, because the editor
 * asks the font service for exactly these weights. Run it again to pick up
 * newly published fonts:
 *
 *   node scripts/build-font-catalog.js
 */
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "src", "data", "googleFonts.ts");

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} answered ${res.status}`);
  const text = await res.text();
  // Google prefixes its JSON with a guard line
  return JSON.parse(text.startsWith(")]}'") ? text.slice(text.indexOf("\n") + 1) : text);
}

const CATEGORY = { "Sans Serif": "s", Serif: "e", Display: "d", Handwriting: "h", Monospace: "m" };

function fontshareCategory(name) {
  const key = String(name || "").toLowerCase();
  if (key.includes("mono")) return "m";
  if (key.includes("serif") && !key.includes("sans")) return "e";
  if (key.includes("slab")) return "e";
  if (key.includes("hand") || key.includes("script")) return "h";
  if (key.includes("display")) return "d";
  return "s";
}

async function main() {
  const google = (await getJson("https://fonts.google.com/metadata/fonts")).familyMetadataList;
  const fontshare = (await getJson("https://api.fontshare.com/v2/fonts?limit=200")).fonts;

  const rows = [];
  const taken = new Set();

  for (const font of [...google].sort((a, b) => a.popularity - b.popularity)) {
    // Icon fonts hold symbols, not letters, so they are no use for text
    if (/Icons|Symbols/.test(font.family)) continue;
    const keys = Object.keys(font.fonts);
    let weights = [...new Set(keys.map((k) => parseInt(k, 10)).filter(Number.isFinite))].sort((a, b) => a - b);
    const weightAxis = (font.axes || []).find((axis) => axis.tag === "wght");
    if (weightAxis) {
      // A variable font can be set at any weight in its range; list the usual steps
      weights = [];
      for (let w = 100; w <= 900; w += 100) if (w >= weightAxis.min && w <= weightAxis.max) weights.push(w);
    }
    if (!weights.length) weights = [400];
    const flags = (keys.some((k) => k.endsWith("i")) ? "i" : "") + (weightAxis ? "v" : "");
    rows.push([font.family, CATEGORY[font.category] || "s", weights.join(" "), flags]);
    taken.add(font.family.toLowerCase());
  }

  for (const font of [...fontshare].sort((a, b) => (b.views || 0) - (a.views || 0))) {
    // Families Google also publishes are loaded from Google
    if (taken.has(font.name.toLowerCase())) continue;
    const upright = font.styles.filter((s) => !s.is_italic && !s.is_variable);
    const weights = [...new Set(upright.map((s) => Math.round(s.weight.weight / 100) * 100))].filter((w) => w >= 100 && w <= 900).sort((a, b) => a - b);
    if (!weights.length) continue;
    rows.push([font.name, fontshareCategory(font.category), weights.join(" "), "", font.slug]);
    taken.add(font.name.toLowerCase());
  }

  const body = rows.map((row) => `  ${JSON.stringify(row)},`).join("\n");
  const source = `/**
 * The font library: every family Falcon can load, with the weights it really has.
 *
 * GENERATED by scripts/build-font-catalog.js from the public Google Fonts and
 * Fontshare directories. Do not edit by hand; run the script again instead.
 */

export type FontCategory =
  | "sans-serif"
  | "serif"
  | "display"
  | "handwriting"
  | "monospace";

export interface GoogleFontMeta {
  family: string;
  category: FontCategory;
  /** The weights this family can be loaded in, e.g. ["400", "700"] */
  variants: string[];
  hasItalic: boolean;
  isVariable: boolean;
  popularityRank: number;
  /** Where the font files come from. Left out for Google Fonts. */
  source?: "fontshare";
  /** The family's name in the Fontshare address */
  slug?: string;
}

const CATEGORY_BY_CODE: Record<string, FontCategory> = { s: "sans-serif", e: "serif", d: "display", h: "handwriting", m: "monospace" };

// family, category code, weights, flags (i = has italics, v = variable), Fontshare slug
type Row = [string, string, string, string, string?];

const ROWS: Row[] = [
${body}
];

export const GOOGLE_FONTS_CATALOG: GoogleFontMeta[] = ROWS.map(([family, code, weights, flags, slug], index) => ({
  family,
  category: CATEGORY_BY_CODE[code] || "sans-serif",
  variants: weights.split(" "),
  hasItalic: flags.includes("i"),
  isVariable: flags.includes("v"),
  popularityRank: index + 1,
  ...(slug ? { source: "fontshare" as const, slug } : {}),
}));
`;
  fs.writeFileSync(OUT, source);
  const fromFontshare = rows.filter((r) => r[4]).length;
  console.log(`wrote ${rows.length} families (${rows.length - fromFontshare} Google Fonts, ${fromFontshare} Fontshare) to ${path.relative(process.cwd(), OUT)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
