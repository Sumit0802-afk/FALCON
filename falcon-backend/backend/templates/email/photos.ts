const PHOTO_HOST = "https://images.unsplash.com/photo-";

export function photoUrl(id: string, width: number, height: number): string {
  return `${PHOTO_HOST}${id}?w=${Math.round(width)}&h=${Math.round(height)}&fit=crop&crop=entropy&auto=format&q=70`;
}

